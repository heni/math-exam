#!/usr/bin/env bash
# Сборка единого question-shorts.pdf: склеивает short.md всех вопросов в один
# markdown с заголовком «# Вопрос NN. ...» на каждый вопрос и \newpage между
# ними. Использование: bash tools/shorts.sh > <combined.md>
set -euo pipefail
cd "$(dirname "$0")/.."

# Орнамент после содержания, перед первым билетом — визуальный разрыв.
# Стоит в теле первым элементом: pandoc ставит оглавление перед телом, так что
# орнамент оказывается внизу той же страницы, а \newpage ниже уносит билеты.
printf '\\begin{center}\\includegraphics[width=0.45\\textwidth]{assets/ornament.pdf}\\end{center}\n\n'

# Страница условных обозначений между содержанием и первым билетом: пометки
# уровней [C]/[A]/[R], устройство билета, общие обозначения преамбулы.
# Собственный \newpage перед текстом: pandoc ставит оглавление перед телом, без
# разрыва легенда слиплась бы со страницей содержания; разрыв после — цикл билетов.
printf '\n\\newpage\n\n'
cat <<'EOF'
# Условные обозначения

**Пометки уровней результатов.** Пометка стоит в заголовке пункта билета и задаёт его вес в ответе:

- **[C] (core)** — ядро ответа: без этого результата ответ неполон. Явная пометка ставится там, где среди похожих пунктов нужно заякорить главное; пункт без пометки считается ядром.
- **[A] (advanced)** — углубление сверх обязательного объёма: материал «в билет с пометкой». Его наличие усиливает ответ, отсутствие не считается пробелом.
- **[R] (reserve)** — специальные критерии и узкие приложения: про запас на уточняющий вопрос экзаменатора.

**Устройство билета.** Стержень темы (основной результат) → определения → леммы → теоремы → у алгоритмоёмких тем раздел «Методы и алгоритмы» → следствия → сжатое приложение за рамками устного ответа. Формулировки совпадают с полным конспектом теории. Один билет — одна страница; вторую страницу занимает только раздел методов.

**Общие обозначения** (общие для всех билетов): $\R^n$ — $n$-мерное вещественное пространство, $\N$ — натуральные числа; $\E$ — математическое ожидание, $\Var$ — дисперсия, $\Prob$ — вероятность; $A\T$ — транспонирование; $\norm{x}$ — норма.
EOF
printf '\n'

for md in questions/*/short.md; do
  [ -e "$md" ] || continue
  title=$(sed -n 's/^title: "\(.*\)"/\1/p' "$md" | head -1)
  # Разрыв перед КАЖДЫМ билетом, включая первый: pandoc ставит оглавление
  # перед телом документа, и без разрыва перед первым билетом содержание
  # слипается с ним.
  printf '\n\\newpage\n\n'
  printf '# %s\n\n' "$title"
  # Тело без YAML-шапки: short.md начинается с блока --- ... ---
  sed -n '/^---$/,/^---$/d; p' "$md" | sed '1{/^$/d}'
  printf '\n'
done
